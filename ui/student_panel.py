"""Student view: choose a subject and paper, sit the exam, submit for marking.

Students only receive papers a teacher has approved, unless demo mode
(ALLOW_STUDENT_ON_DEMAND) is on and none exists, in which case an unreviewed
draft is generated, clearly labelled and queued for teacher review.
"""
from __future__ import annotations

import time

import streamlit as st

from config import exam_specs, settings
from config.llm import LLMProvider
from core import exam_store, syllabus
from core.grader import grade_attempt
from core.schemas import Exam, ExamConfig, QuestionType, StudentAnswer
from core.vector_store import VectorStore
from ui import components as ui
from ui.teacher_panel import create_draft


def render(store: VectorStore, llm: LLMProvider) -> None:
    ui.page_header("Student Panel", "Pick a subject and paper, sit a fresh practice exam, and get marked feedback.")
    started = st.session_state.get("exam_started_at")
    exam: Exam | None = st.session_state.get("exam")

    if not started:
        _selection(store, llm, exam)
        return
    _sit_exam(exam, llm)


# --- Choosing a paper ---------------------------------------------------------------------
def _format_label(fmt: tuple[str, str, str, int]) -> str:
    key, section, difficulty, n = fmt
    spec = exam_specs.PAPER_SPECS[key]
    if spec.questions:
        qs = spec.questions_for(section)
        marks, minutes = sum(q.marks for q in qs), spec.duration_for(section)
        return f"{spec.title} · {section} · {marks} marks · {minutes} min · {difficulty}"
    return f"{spec.title} · {n} questions · {difficulty}"


def _selection(store: VectorStore, llm: LLMProvider, exam: Exam | None) -> None:
    subjects = exam_store.approved_subjects()
    if settings.ALLOW_STUDENT_ON_DEMAND:
        subjects = sorted(set(subjects) | {s for s in store.subjects() if (syl := syllabus.load(s)) and syl.approved})
    if not subjects:
        st.info("No practice papers are available yet. Your teacher needs to approve one first.")
        return

    st.info("In production this view runs fullscreen with tab-switch detection and copy/paste restrictions. "
            "These are switched off in the demo.", icon="🔒")
    subject = st.selectbox("Subject", subjects)
    formats = exam_store.approved_formats(subject)
    if settings.ALLOW_STUDENT_ON_DEMAND:
        for spec in exam_specs.formats_for_subject(subject):
            for section in spec.sections or [""]:
                for n in ([0] if spec.sections else [5, 10]):
                    for diff in ("Foundation", "Higher"):
                        fmt = (spec.key, section, diff, n)
                        if fmt not in formats:
                            formats.append(fmt)
    if not formats:
        st.info(f"No approved {subject} papers yet.")
        return
    fmt = st.selectbox("Exam", formats, format_func=_format_label)

    if st.button("Get my paper", type="primary"):
        attempted = st.session_state.setdefault("attempted_ids", set())
        rec = exam_store.pick_approved(subject, fmt, exclude=attempted)
        if rec is None:
            rec = _generate_on_demand(store, llm, subject, fmt)
        if rec is not None:
            st.session_state.update(exam=rec.exam, mark_scheme=rec.mark_scheme, result=None, exam_started_at=None)
            st.rerun()

    if exam is not None and st.session_state.get("result") is None:
        st.divider()
        st.markdown(f"### {exam.title}")
        st.caption(exam.paper_title)
        st.markdown(ui.badge(f"{exam.total_marks} marks") + ui.badge(f"{exam.duration_minutes} minutes")
                    + ui.badge(exam.config.difficulty), unsafe_allow_html=True)
        if exam.status != "approved":
            st.warning("This paper was generated by AI and has not yet been reviewed by a teacher. "
                       "Some questions may be outside the syllabus.")
        st.write("The timer starts when you press Start. Answer every question, then submit.")
        if st.button("Start exam", type="primary"):
            st.session_state["exam_started_at"] = time.time()
            st.rerun()


def _generate_on_demand(store: VectorStore, llm: LLMProvider, subject: str, fmt) -> object | None:
    if not settings.ALLOW_STUDENT_ON_DEMAND:
        st.warning("No approved paper is available for this exam yet. Please ask your teacher.")
        return None
    key, section, difficulty, n = fmt
    config = ExamConfig(subject=subject, paper_key=key, section=section, num_questions=n, difficulty=difficulty)
    with ui.friendly_errors("generate your paper"):
        exam = create_draft(config, store, llm, origin="student_on_demand")
        return exam_store.load(exam.exam_id)
    return None


# --- Sitting the exam -----------------------------------------------------------------------
def _sit_exam(exam: Exam, llm: LLMProvider) -> None:
    started = st.session_state["exam_started_at"]
    st.markdown(f"### {exam.title}")
    st.caption(f"{exam.paper_title} · {exam.total_marks} marks · {exam.duration_minutes} minutes")
    if exam.status != "approved":
        st.warning("AI draft not yet reviewed by a teacher.")

    _timer(exam.duration_minutes)
    ui.render_sources(exam)

    with st.form(f"exam_form_{exam.exam_id}"):
        section = None
        for q in exam.questions:
            if q.section != section:
                section = q.section
                st.subheader(section)
            with st.container(border=True):
                st.markdown(ui.question_html(q.number, q.marks, q.question_text), unsafe_allow_html=True)
                key = f"ans_{exam.exam_id}_{q.number}"
                if q.question_type in (QuestionType.MCQ, QuestionType.TRUE_FALSE):
                    st.radio("Your answer", q.options, index=None, key=key, label_visibility="collapsed")
                elif q.question_type == QuestionType.MULTI_SELECT:
                    st.caption("Tick the four statements you think are true.")
                    for i, opt in enumerate(q.options):
                        st.checkbox(f"{chr(65 + i)}. {opt}", key=f"{key}_{i}")
                else:
                    height = 140 if q.marks <= 4 else 260 if q.marks <= 12 else 380
                    st.text_area("Your answer", key=key, height=height, label_visibility="collapsed",
                                 placeholder="Type your answer here...")
        submitted = st.form_submit_button("Submit exam", type="primary", use_container_width=True)

    if submitted:
        _submit(exam, llm, int(time.time() - started))


@st.fragment(run_every=1)
def _timer(duration_minutes: int) -> None:
    started = st.session_state.get("exam_started_at")
    if not started:
        return
    elapsed = int(time.time() - started)
    remaining = duration_minutes * 60 - elapsed
    c1, c2 = st.columns(2)
    c1.metric("Time elapsed", f"{elapsed // 60:02d}:{elapsed % 60:02d}")
    if remaining >= 0:
        c2.metric("Time remaining", f"{remaining // 60:02d}:{remaining % 60:02d}")
    else:
        c2.metric("Time remaining", "00:00", delta=f"{-remaining // 60} min over", delta_color="inverse")


def _collect_answers(exam: Exam) -> list[StudentAnswer]:
    answers = []
    for q in exam.questions:
        key = f"ans_{exam.exam_id}_{q.number}"
        if q.question_type in (QuestionType.MCQ, QuestionType.TRUE_FALSE):
            choice = st.session_state.get(key)
            answers.append(StudentAnswer(number=q.number, selected_options=[choice] if choice else []))
        elif q.question_type == QuestionType.MULTI_SELECT:
            chosen = [opt for i, opt in enumerate(q.options) if st.session_state.get(f"{key}_{i}")]
            answers.append(StudentAnswer(number=q.number, selected_options=chosen))
        else:
            answers.append(StudentAnswer(number=q.number, text=st.session_state.get(key, "")))
    return answers


def _submit(exam: Exam, llm: LLMProvider, elapsed: int) -> None:
    answers = _collect_answers(exam)
    with ui.friendly_errors("mark your exam"):
        with st.spinner("Marking your answers..."):
            result = grade_attempt(exam, st.session_state["mark_scheme"], answers, llm, elapsed)
        exam_store.save_attempt(result)
        st.session_state.setdefault("attempted_ids", set()).add(exam.exam_id)
        st.session_state.update(result=result, exam_started_at=None)
        ui.goto("Results")
